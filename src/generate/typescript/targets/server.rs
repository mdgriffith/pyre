pub fn generate_schema(
    context: &typecheck::Context,
    database: &ast::Database,
    base_out_dir: &Path,
    files: &mut Vec<filesystem::GeneratedFile<String>>,
) {
    let mut content = String::new();
    content.push_str("// This file is generated by Pyre. Do not edit by hand.\n\n");
    content.push_str("import type { Client } from '@libsql/client';\n");
    content.push_str(
        "import { ensureDatabase as pyreEnsureDatabase, type ExternalIdentity } from '@pyre/server/schema';\n\n",
    );
    content.push_str("const database = (schemaName: string, schemaSource: string, externalIdentities: ExternalIdentity[]) => ({\n");
    content.push_str("  schemaSource,\n");
    content.push_str(
        "  ensureDatabase: (db: Client) => pyreEnsureDatabase(db, schemaName, schemaSource, externalIdentities),\n",
    );
    content.push_str("});\n\n");
    content.push_str("export const databases = {\n");
    for schema in &database.schemas {
        let source = crate::generate::to_string::standalone_schema_to_string(context, schema);
        let identities = crate::typecheck::project_external_identities(context, &schema.namespace);
        content.push_str(&format!(
            "  {}: database({}, {}, {}),\n",
            serde_json::to_string(&schema.namespace).expect("namespace should serialize"),
            serde_json::to_string(&schema.namespace).expect("namespace should serialize"),
            serde_json::to_string(&source).expect("schema should serialize"),
            serde_json::to_string(&identities).expect("identities should serialize"),
        ));
    }
    content.push_str("} as const;\n");

    files.push(generate_text_file(
        base_out_dir.join("databases.ts"),
        content,
    ));

    generate_seed(context, database, base_out_dir, files);
}

fn generate_seed(
    context: &typecheck::Context,
    database: &ast::Database,
    base_out_dir: &Path,
    files: &mut Vec<filesystem::GeneratedFile<String>>,
) {
    let mut content = String::new();

    content.push_str("// This file is generated by Pyre. Do not edit by hand.\n\n");
    content.push_str("import type { Client } from '@libsql/client';\n");
    content.push_str("import { seed as pyreSeed, type SeedResult } from '@pyre/server/query';\n\n");
    content.push_str("export type FixtureJson = null | boolean | number | string | FixtureJson[] | { [key: string]: FixtureJson };\n\n");
    content.push_str(&seed_custom_types(context));
    let single = database.schemas.len() == 1;
    for (index, schema) in database.schemas.iter().enumerate() {
        let prefix = if single {
            "Seed".to_string()
        } else {
            format!("SeedDb{index}")
        };
        content.push_str(&to_seed_types(context, &schema.namespace, &prefix));
        let binding = if single {
            "export const seed".into()
        } else {
            format!("const seedDb{index}")
        };
        let namespace =
            serde_json::to_string(&schema.namespace).expect("namespace should serialize");
        content.push_str(&format!("{binding} = (db: Client, input: {prefix}Input): Promise<SeedResult> => pyreSeed(db, input, {{ namespace: {namespace} }});\n\n"));
    }
    if !single {
        content.push_str("export const fixtures = {\n");
        for (index, schema) in database.schemas.iter().enumerate() {
            let namespace =
                serde_json::to_string(&schema.namespace).expect("namespace should serialize");
            content.push_str(&format!("  [{namespace}]: {{ seed: seedDb{index} }},\n"));
        }
        content.push_str("} as const;\n\n");
        content.push_str("export type SeedInput<N extends keyof typeof fixtures> = Parameters<(typeof fixtures)[N]['seed']>[1];\n");
    }

    files.push(generate_text_file(base_out_dir.join("seed.ts"), content));
}

pub fn generate_queries(
    _context: &typecheck::Context,
    _all_query_info: &HashMap<String, typecheck::QueryInfo>,
    query_list: &ast::QueryList,
    base_out_dir: &Path,
    files: &mut Vec<filesystem::GeneratedFile<String>>,
) {
    let mut content = String::new();

    content.push_str("// This file is generated by Pyre. Do not edit by hand.\n\n");
    content.push_str("import type { QueryMap, QueryMetadata } from '@pyre/server/query';\n\n");
    content.push_str("export { databases } from './databases';\n\n");
    content.push_str("export * from './seed';\n\n");

    for operation in &query_list.queries {
        if let ast::QueryDef::Query(q) = operation {
            let query_name = q.name.to_string();
            content.push_str(&format!(
                "import {{ meta as {} }} from './core/queries/metadata/{}';\n",
                query_name,
                crate::ext::string::decapitalize(&query_name)
            ));
            content.push_str(&format!(
                "import {{ sql as {}Sql, syncSql as {}SyncSql }} from './core/queries/sql/{}';\n",
                query_name,
                query_name,
                crate::ext::string::decapitalize(&query_name)
            ));
        }
    }

    content.push_str("\n");

    for operation in &query_list.queries {
        if let ast::QueryDef::Query(q) = operation {
            content.push_str(&format!(
                "const {}Query: QueryMetadata = {{\n  ...{},\n  sql: {}Sql,\n  ...(Array.isArray({}SyncSql) ? {{ syncSql: {}SyncSql }} : {{}})\n}};\n\n",
                q.name, q.name, q.name, q.name, q.name
            ));
        }
    }

    content.push_str("export const queries: QueryMap = {\n");
    let mut first = true;
    for operation in &query_list.queries {
        if let ast::QueryDef::Query(q) = operation {
            if !first {
                content.push_str(",\n");
            }
            content.push_str(&format!("  [{}.id]: {}Query", q.name, q.name));
            first = false;
        }
    }
    content.push_str("\n};\n\n");

    files.push(generate_text_file(base_out_dir.join("server.ts"), content));
}

fn seed_custom_types(context: &typecheck::Context) -> String {
    let mut result = String::new();
    let mut types = context.types.iter().collect::<Vec<_>>();
    types.sort_by_key(|(name, _)| *name);
    for (name, (definition, type_)) in types {
        let (crate::error::DefInfo::Def(_), typecheck::Type::OneOf { variants }) =
            (definition, type_)
        else {
            continue;
        };
        result.push_str(&format!("export type SeedCustom_{name} =\n"));
        for variant in variants {
            let tag = string::quote(&variant.name);
            result.push_str(&format!("  | {{ _type: {tag}"));
            let columns = variant
                .fields
                .as_ref()
                .map(|fields| ast::collect_columns(fields))
                .unwrap_or_default();
            for column in &columns {
                let optional = if seed_nullable(column) { "?" } else { "" };
                result.push_str(&format!(
                    "; {}{optional}: {}",
                    string::quote(&column.name),
                    seed_column_type(column)
                ));
            }
            result.push_str(" }");
            if columns.is_empty() {
                result.push_str(&format!(" | {tag}"));
            }
            result.push('\n');
        }
        result.push_str("  ;\n\n");
    }
    result
}

fn to_seed_types(context: &typecheck::Context, namespace: &str, prefix: &str) -> String {
    let mut result = String::new();
    let mut tables: Vec<&typecheck::Table> = context
        .tables
        .values()
        .filter(|table| table.schema == namespace)
        .collect();
    tables.sort_by(|a, b| {
        let a_table_name = ast::get_tablename(&a.record.name, &a.record.fields);
        let b_table_name = ast::get_tablename(&b.record.name, &b.record.fields);
        a_table_name.cmp(&b_table_name)
    });

    for table in &tables {
        let table_name = ast::get_tablename(&table.record.name, &table.record.fields);
        let type_name = seed_row_type_name(prefix, &table_name);
        result.push_str(&format!("export type {} = {{\n", type_name));

        for column in ast::collect_columns(&table.record.fields) {
            if ast::is_sequence(&column) {
                continue;
            }
            let ts_type = seed_column_type(&column);
            result.push_str(&format!(
                "  {}?: {};\n",
                string::quote(&column.name),
                ts_type
            ));
        }

        let links = ast::collect_links(&table.record.fields);
        let primary_key_name = ast::get_primary_id_field_name(&table.record.fields);
        for link in links {
            let linked_table = typecheck::get_linked_table(context, &link).expect(&format!(
                "Failed to find linked table '{}' in context. This indicates a schema error.",
                link.foreign.table
            ));
            if linked_table.schema != namespace {
                continue;
            }
            let linked_table_name =
                ast::get_tablename(&linked_table.record.name, &linked_table.record.fields);
            let linked_type_name = seed_row_type_name(prefix, &linked_table_name);
            let is_parent_to_child = link.local_ids.iter().all(|id| {
                primary_key_name
                    .as_ref()
                    .map(|pk| id == pk)
                    .unwrap_or(false)
            });
            let link_type = if is_parent_to_child {
                format!("{}[]", linked_type_name)
            } else {
                linked_type_name
            };
            result.push_str(&format!(
                "  {}?: {};\n",
                string::quote(&link.link_name),
                link_type
            ));
        }

        result.push_str("};\n\n");
    }

    result.push_str(&format!("export type {prefix}Input = {{\n"));
    for table in &tables {
        let table_name = ast::get_tablename(&table.record.name, &table.record.fields);
        result.push_str(&format!(
            "  {}?: {}[];\n",
            string::quote(&table_name),
            seed_row_type_name(prefix, &table_name)
        ));
    }
    result.push_str("};\n\n");

    result
}

fn seed_row_type_name(prefix: &str, table_name: &str) -> String {
    let mut result = String::from(prefix);
    let mut capitalize_next = true;
    for ch in table_name.chars() {
        if ch.is_ascii_alphanumeric() {
            if capitalize_next {
                result.push(ch.to_ascii_uppercase());
                capitalize_next = false;
            } else {
                result.push(ch);
            }
        } else {
            capitalize_next = true;
        }
    }
    result.push_str("Row");
    result
}

fn seed_column_type(column: &ast::Column) -> String {
    let base = seed_column_type_inner(&column.type_);
    if column.nullable && !matches!(column.type_, ast::ColumnType::Nullable(_)) {
        format!("{} | null", base)
    } else {
        base
    }
}

fn seed_nullable(column: &ast::Column) -> bool {
    column.nullable || matches!(column.type_, ast::ColumnType::Nullable(_))
}

fn seed_column_type_inner(type_: &ast::ColumnType) -> String {
    match type_ {
        ast::ColumnType::DateTime => "number | string".to_string(),
        ast::ColumnType::Json => "FixtureJson".to_string(),
        ast::ColumnType::JsonTyped(inner) => seed_column_type_inner(inner),
        ast::ColumnType::List(inner) => {
            format!("Array<{}>", seed_column_type_inner(inner))
        }
        ast::ColumnType::Dict(inner) => {
            format!("{{ [key: string]: {} }}", seed_column_type_inner(inner))
        }
        ast::ColumnType::Nullable(inner) => {
            format!("{} | null", seed_column_type_inner(inner))
        }
        ast::ColumnType::Custom(name) => format!("SeedCustom_{name}"),
        _ => common::column_type_to_ts_type(type_, true),
    }
}
